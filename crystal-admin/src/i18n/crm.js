/**
 * THE CRM SCREENS' WORDS, in every language the console speaks - organised by
 * screen, the way i18n/dictionaries.js is.
 *
 * Two parts:
 *
 *   SENTENCES - en / zh / ru below - are addressed: `translate('crm.events.approve')`.
 *   They become the `crm` section of each catalogue, with ONE SECTION PER
 *   SCREEN, named after the screen's file (crm.customers, crm.customerImport,
 *   crm.registrationReview, crm.customer360, crm.events, ...). A sentence used
 *   by more than one screen lives in crm.common; the CRM's shared pieces
 *   (pickers, search, tables) in crm.components. The comment above each
 *   section names its files.
 *
 *   WORDS - words.en / words.zh / words.ru - are looked up by their English:
 *   a column label, a code turned into a word, a name that arrives as data.
 *   They become `vocabulary.crm`, grouped the same way: one group per screen,
 *   `common` for words several screens use, `codes` for the words
 *   pages/crm/shared.jsx WORDS turns codes into, and `data` for names that
 *   arrive from the API or the basic data and appear in no file.
 *
 * ADDING A STRING: put it in the section of the screen that shows it, in all
 * three languages. When a second screen starts using it, move it to common.
 * Every address and every word exists in all three languages, which is what
 * i18n.test.js and dictionaryHealth.test.js hold the whole catalogue to.
 */

