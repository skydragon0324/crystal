/**
 * THE CONSOLE'S TRANSLATIONS, in sections.
 *
 * The key used to BE the English text - `t('Save')` - which read well at the
 * call site and made one sentence impossible to find among four hundred
 * others. Editing an English word also moved the key, which orphaned its
 * Chinese silently.
 *
 * So a key is now an ADDRESS: `table.empty`, `pagination.page`,
 * `catalog.products.hero`. Two rules decide which section a string is in:
 *
 *   A SHARED VOCABULARY gets its own section. table, pagination, form, excel,
 *   datepicker, editor, dialog, layout - these are the words that appear on
 *   every screen, and somebody changing how this console says "nothing here
 *   yet" should find every instance of it in one place.
 *
 *   EVERYTHING ELSE LIVES WITH ITS SCREEN. The strings on one page are one
 *   section - `catalog.products`, `members.feedback` - so fixing the wording
 *   of a page means reading one block, not grepping a flat list.
 *
 * A string used by more than one screen is in `common`, because the moment it
 * has two callers it is no longer that page's word.
 *
 * Sections:
 *
 *   analysis      10
 *   app           1
 *   base          6
 *   blog          3
 *   catalog       11
 *   common        30
 *   company       2
 *   components    31
 *   dashboard     14
 *   datepicker    5
 *   dialog        11
 *   editor        30
 *   excel         7
 *   form          10
 *   layout        7
 *   management    9
 *   members       17
 *   pagination    9
 *   service       55
 *   signin        11
 *   support       2
 *   table         12
 *
 * TWO LOOKUPS, and the second is why dynamic labels still translate. A key
 * with a dot is resolved as a path through these objects; anything else is
 * looked up by its ENGLISH TEXT against the English catalogue. That second
 * path is what `t(item.label)` needs - a nav label or a page name out of the
 * database is not a key and never will be. See i18n/index.js.
 */

