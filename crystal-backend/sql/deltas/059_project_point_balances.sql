-- ---------------------------------------------------------------------
-- Delta 059 - reward points per business system, and a company-wide total.
--
-- Every project (business system) runs its own reward points by its own
-- rules, and the CRM does not re-create them or follow their movements. It
-- keeps one figure per business-system account linked to a customer - the
-- points that account holds there - in crm_reward_points. A customer with two
-- accounts in one system has two rows.
--
-- The company-wide score is NOT stored. It is worked out every time, from
-- those rows and each project's point_weight (Settings > Projects): the sum of
-- points times weight (v_crm_party_company_points). A project whose weight is
-- left empty is shown but not counted - no 1:1 rate is assumed for it.
--
-- Rows are entered by hand for now; the departments' systems will send them
-- (POST /api/integration/crm/point-balances) and a sheet can load them.
--
-- The CRM's own points ledger (crm_point_account, crm_point_event) is left as
-- it is and is not part of the company-wide score.
--
-- Safe to run twice and on a database built from the current schema.sql.
-- ---------------------------------------------------------------------

ALTER TABLE crm_project ADD COLUMN IF NOT EXISTS point_weight numeric(12,6) NULL;
ALTER TABLE crm_project DROP CONSTRAINT IF EXISTS chk_crm_project_point_weight;
ALTER TABLE crm_project ADD CONSTRAINT chk_crm_project_point_weight CHECK (point_weight IS NULL OR point_weight >= 0);
COMMENT ON COLUMN crm_project.point_weight IS 'Company-wide points one of this project''s reward points is worth. NULL = its points are shown but not counted in the company-wide score.';

CREATE TABLE IF NOT EXISTS crm_reward_points (
    reward_points_id                   bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_account_id                 bigint         NOT NULL REFERENCES crm_project_account(project_account_id) ON DELETE CASCADE,
    points                             numeric(20,4)  NOT NULL,
    as_of                              timestamptz    NOT NULL DEFAULT now(),
    source                             varchar(10)    NOT NULL DEFAULT 'MANUAL' CHECK (source IN ('MANUAL','API','IMPORT')),
    note                               varchar(500)   NULL,
    updated_by_manager_id              integer        NULL REFERENCES managers(id) ON DELETE SET NULL,
    created_at                         timestamptz    NOT NULL DEFAULT now(),
    updated_at                         timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT uq_crm_reward_points_account UNIQUE (project_account_id)
);
COMMENT ON TABLE crm_reward_points IS 'The reward points one business-system account holds in its own system, as last entered or reported. One row per linked account; the customer and the system come from crm_project_account. Movements are not kept.';
COMMENT ON COLUMN crm_reward_points.points IS 'The points the account holds in its business system.';
COMMENT ON COLUMN crm_reward_points.as_of IS 'When the figure was true: the system''s own time when it sends one, else when it was entered.';
COMMENT ON COLUMN crm_reward_points.source IS 'MANUAL (entered in the console), API (sent by the business system), IMPORT (an Excel sheet).';

/*
 * The company-wide score of each customer, never stored: every live linked
 * account's points times its project's weight. Points of a project with no
 * weight are counted in uncounted_systems, so a screen can say the score
 * leaves something out.
 */
CREATE OR REPLACE VIEW v_crm_party_company_points AS
SELECT account.party_pk,
       ROUND(COALESCE(SUM(reward.points * project.point_weight), 0), 4)      AS company_points,
       COUNT(*) FILTER (WHERE project.point_weight IS NOT NULL)              AS counted_systems,
       COUNT(*) FILTER (WHERE project.point_weight IS NULL)                  AS uncounted_systems
  FROM crm_reward_points reward
  JOIN crm_project_account account ON account.project_account_id = reward.project_account_id
  JOIN crm_project project ON project.project_id = account.project_id
 WHERE account.unlinked_at IS NULL
 GROUP BY account.party_pk;
COMMENT ON VIEW v_crm_party_company_points IS 'Company-wide points per customer: each linked account''s reward points times its project''s weight. Never stored. Points of projects without a weight are counted in uncounted_systems, not in the score.';

/* The analysis metric reads the company-wide score. */
UPDATE crm_metric_definition
   SET metric_name = 'Company-wide points',
       description = 'Each business system''s reward points times its project''s weight (v_crm_party_company_points) - for ranking only, never for spending.'
 WHERE metric_code = 'POINTS_BALANCE';

/* The point types' own comment named types that are not seeded. */
COMMENT ON TABLE crm_point_type IS 'A point currency of the CRM''s own ledger. Currencies are not interchangeable (karaoke points cannot buy an app). Seeded: ACTIVITY, SOFT, REGISTER, MEMBER.';
