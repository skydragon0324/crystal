-- =====================================================================
-- Delta 038 - a person's job is a choice from a list, a person can be
-- marked as checked by staff, and an organization has a location.
--
--   crm_job_title                   NEW: the job list (seeded from the vendor's JOBS)
--   crm_person.job_title            varchar  -> job_title_id int -> crm_job_title
--   crm_person.nationality_code     dropped
--   crm_person.preferred_language   dropped
--   crm_person.id_card_hash         dropped
--   crm_person.id_card_masked       -> is_checked_manually boolean
--   crm_organization.headquarters_location_id -> location_id
--
-- A job title typed before this delta is not lost: every distinct value that
-- is not already on the list is added to it, and the person points at it.
-- =====================================================================

CREATE TABLE crm_job_title (
    job_title_id                       int            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_code                           varchar(30)    NOT NULL UNIQUE,
    job_name                           varchar(100)   NOT NULL UNIQUE,
    sort_order                         smallint       NOT NULL DEFAULT 0,
    is_active                          boolean        NOT NULL DEFAULT true
);
COMMENT ON TABLE crm_job_title IS 'The job titles a person can be given. Seeded from the vendor JOBS list; edited at /admin/crm/settings.';

