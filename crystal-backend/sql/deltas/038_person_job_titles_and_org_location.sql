/* the titles people already have, so none is lost */
INSERT INTO crm_job_title (job_code, job_name, sort_order)
SELECT left(upper(regexp_replace(trim(t.job_title), '[^A-Za-z0-9]+', '_', 'g')), 24) || '_' || row_number() OVER (ORDER BY t.job_title),
       left(trim(t.job_title), 100), 100
  FROM (SELECT DISTINCT trim(job_title) AS job_title FROM crm_person
         WHERE job_title IS NOT NULL AND trim(job_title) <> '') t
 WHERE NOT EXISTS (SELECT 1 FROM crm_job_title j WHERE lower(j.job_name) = lower(t.job_title));

ALTER TABLE crm_person ADD COLUMN job_title_id int NULL REFERENCES crm_job_title(job_title_id);
UPDATE crm_person p SET job_title_id = j.job_title_id
  FROM crm_job_title j
 WHERE p.job_title IS NOT NULL AND lower(j.job_name) = lower(trim(p.job_title));

ALTER TABLE crm_person ADD COLUMN is_checked_manually boolean NOT NULL DEFAULT false;

ALTER TABLE crm_person DROP COLUMN job_title;
ALTER TABLE crm_person DROP COLUMN nationality_code;
ALTER TABLE crm_person DROP COLUMN preferred_language;
ALTER TABLE crm_person DROP COLUMN id_card_hash;
ALTER TABLE crm_person DROP COLUMN id_card_masked;

CREATE INDEX idx_crm_person_job ON crm_person(job_title_id) WHERE job_title_id IS NOT NULL;
CREATE INDEX idx_crm_person_unchecked ON crm_person(party_id) WHERE NOT is_checked_manually;
COMMENT ON COLUMN crm_person.is_checked_manually IS 'true once a manager has reviewed this person by hand. Who and when is in audit_log.';

ALTER TABLE crm_organization RENAME COLUMN headquarters_location_id TO location_id;
