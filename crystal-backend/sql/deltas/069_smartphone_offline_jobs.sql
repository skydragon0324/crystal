-- ---------------------------------------------------------------------
-- Delta 069 - linking every customer to SMARTPHONE_OFFLINE, as a job.
--
-- Customers are linked to the SMARTPHONE_OFFLINE system by their phone
-- numbers. With hundreds of thousands of customers that is hours of work, so
-- it is a JOB kept here rather than a run kept in the server's memory:
--
--   crm_smartphone_offline_job          one per "link" - all customers, a
--                                       range of customer numbers, or the
--                                       failures of an earlier job - with its
--                                       progress: where it has got to
--                                       (last_party_pk), the counts so far
--   crm_smartphone_offline_job_failure  every number that could not be looked
--                                       up, so a job can retry exactly those
--
-- A job goes through its customers in chunks in customer-number order and
-- saves after each, so a server that stops part-way resumes from the last
-- chunk it finished. Only one job is RUNNING or PAUSED at a time.
--
-- Safe to run twice, and on a database built from the current schema.sql.
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS crm_smartphone_offline_job (
    job_id                             bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope                              varchar(10)    NOT NULL CHECK (scope IN ('ALL', 'RANGE', 'RETRY')),
    from_party_pk                      bigint         NULL,
    to_party_pk                        bigint         NULL,
    retry_of_job_id                    bigint         NULL REFERENCES crm_smartphone_offline_job(job_id),
    status                             varchar(10)    NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING', 'PAUSED', 'DONE', 'CANCELLED', 'FAILED')),
    total                              integer        NOT NULL DEFAULT 0,
    done                               integer        NOT NULL DEFAULT 0,
    last_party_pk                      bigint         NULL,
    summary                            jsonb          NOT NULL DEFAULT '{}'::jsonb,
    error                              text           NULL,
    started_by_manager_id              integer        NULL REFERENCES managers(id) ON DELETE SET NULL,
    started_at                         timestamptz    NOT NULL DEFAULT now(),
    updated_at                         timestamptz    NOT NULL DEFAULT now(),
    finished_at                        timestamptz    NULL
);
COMMENT ON TABLE crm_smartphone_offline_job IS 'A job linking customers to SMARTPHONE_OFFLINE users by phone number: its scope, where it has got to (last_party_pk) and its counts so far.';
-- One job at a time: at most one row is RUNNING or PAUSED.
CREATE UNIQUE INDEX IF NOT EXISTS uq_crm_smartphone_offline_job_active ON crm_smartphone_offline_job ((true)) WHERE status IN ('RUNNING', 'PAUSED');

CREATE TABLE IF NOT EXISTS crm_smartphone_offline_job_failure (
    job_failure_id                     bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id                             bigint         NOT NULL REFERENCES crm_smartphone_offline_job(job_id) ON DELETE CASCADE,
    party_pk                           bigint         NOT NULL,
    phone                              varchar(50)    NOT NULL,
    error                              text           NULL,
    created_at                         timestamptz    NOT NULL DEFAULT now()
);
COMMENT ON TABLE crm_smartphone_offline_job_failure IS 'A phone number a linking job could not look up in SMARTPHONE_OFFLINE, and why - what a retry job asks about again.';
CREATE INDEX IF NOT EXISTS idx_crm_smartphone_offline_job_failure ON crm_smartphone_offline_job_failure(job_id, party_pk);
