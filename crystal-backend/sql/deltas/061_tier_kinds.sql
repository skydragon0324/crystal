-- ---------------------------------------------------------------------
-- Delta 061 - several kinds of tier per project, one tier per account and kind.
--
-- A project may rank its customers on more than one ladder at once - an
-- activity level, a customer grade, a card class, and others it adds later.
-- The kinds are a managed list (crm_tier_kind, Settings > Tier kinds) instead
-- of a fixed CHECK; each project tier belongs to one kind.
--
-- A membership is now one ACCOUNT's place on one KIND of ladder in its
-- project: unique per (project_account_id, tier_kind). A customer with two
-- accounts in a project, ranked on two kinds there, has four. Its tier must be
-- of its own project AND its own kind (composite key). Memberships from
-- before are given the customer's primary live account in that project and
-- the kind of their current tier (LEVEL when they have none); one whose
-- customer has no account there keeps project_account_id NULL and stays
-- unique per (party, project, kind).
--
-- Safe to run twice and on a database built from the current schema.sql.
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS crm_tier_kind (
    tier_kind_id                       smallint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind_code                          varchar(20)    NOT NULL,
    kind_name                          varchar(100)   NOT NULL,
    sort_no                            smallint       NULL,
    is_active                          boolean        NOT NULL DEFAULT true,
    CONSTRAINT uq_crm_tier_kind_code UNIQUE (kind_code)
);
COMMENT ON TABLE crm_tier_kind IS 'The kinds of tier ladder a project can rank customers on (level, grade, card class, ...). Managed in Settings > Tier kinds.';
INSERT INTO crm_tier_kind (kind_code, kind_name, sort_no) VALUES
 ('LEVEL', 'Level', 1), ('GRADE', 'Grade', 2), ('CARD_CLASS', 'Card class', 3)
ON CONFLICT (kind_code) DO NOTHING;

-- The membership keys below hang on keys of tiers and accounts that are
-- remade here; they are dropped first and made again further down.
ALTER TABLE crm_membership DROP CONSTRAINT IF EXISTS fk_crm_membership_tier;
ALTER TABLE crm_membership DROP CONSTRAINT IF EXISTS fk_crm_membership_account;

-- Tiers: their kind is one of the managed kinds.
INSERT INTO crm_tier_kind (kind_code, kind_name)
SELECT DISTINCT tier.tier_kind, tier.tier_kind FROM crm_project_tier tier
ON CONFLICT (kind_code) DO NOTHING;
ALTER TABLE crm_project_tier DROP CONSTRAINT IF EXISTS crm_project_tier_tier_kind_check;
ALTER TABLE crm_project_tier DROP CONSTRAINT IF EXISTS fk_crm_project_tier_kind;
ALTER TABLE crm_project_tier ADD CONSTRAINT fk_crm_project_tier_kind FOREIGN KEY (tier_kind) REFERENCES crm_tier_kind(kind_code) ON UPDATE CASCADE;
ALTER TABLE crm_project_tier DROP CONSTRAINT IF EXISTS uq_crm_tier_project_kind;
ALTER TABLE crm_project_tier ADD CONSTRAINT uq_crm_tier_project_kind UNIQUE (project_tier_id, project_id, tier_kind);
COMMENT ON COLUMN crm_project_tier.tier_kind IS 'The ladder this tier is on (crm_tier_kind). A member holds one tier per kind.';

-- Accounts: (id, project) as a key, so a membership's account is of its own project.
ALTER TABLE crm_project_account DROP CONSTRAINT IF EXISTS uq_crm_project_account_project;
ALTER TABLE crm_project_account ADD CONSTRAINT uq_crm_project_account_project UNIQUE (project_account_id, project_id);

-- Memberships: per account and kind.
ALTER TABLE crm_membership ADD COLUMN IF NOT EXISTS project_account_id bigint NULL;
ALTER TABLE crm_membership ADD COLUMN IF NOT EXISTS tier_kind varchar(20) NULL;

UPDATE crm_membership membership SET tier_kind = tier.tier_kind
  FROM crm_project_tier tier
 WHERE tier.project_tier_id = membership.current_tier_id AND membership.tier_kind IS NULL;
UPDATE crm_membership SET tier_kind = 'LEVEL' WHERE tier_kind IS NULL;
UPDATE crm_membership membership SET project_account_id = (
       SELECT account.project_account_id FROM crm_project_account account
        WHERE account.party_pk = membership.party_pk AND account.project_id = membership.project_id AND account.unlinked_at IS NULL
        ORDER BY account.is_primary DESC, account.project_account_id LIMIT 1)
 WHERE membership.project_account_id IS NULL;

ALTER TABLE crm_membership ALTER COLUMN tier_kind SET NOT NULL;
ALTER TABLE crm_membership DROP CONSTRAINT IF EXISTS fk_crm_membership_kind;
ALTER TABLE crm_membership ADD CONSTRAINT fk_crm_membership_kind FOREIGN KEY (tier_kind) REFERENCES crm_tier_kind(kind_code) ON UPDATE CASCADE;
ALTER TABLE crm_membership DROP CONSTRAINT IF EXISTS fk_crm_membership_account;
ALTER TABLE crm_membership ADD CONSTRAINT fk_crm_membership_account FOREIGN KEY (project_account_id, project_id) REFERENCES crm_project_account(project_account_id, project_id);
ALTER TABLE crm_membership DROP CONSTRAINT IF EXISTS fk_crm_membership_tier;
ALTER TABLE crm_membership ADD CONSTRAINT fk_crm_membership_tier FOREIGN KEY (current_tier_id, project_id, tier_kind) REFERENCES crm_project_tier(project_tier_id, project_id, tier_kind) ON UPDATE CASCADE;

ALTER TABLE crm_membership DROP CONSTRAINT IF EXISTS uq_crm_membership;
CREATE UNIQUE INDEX IF NOT EXISTS uq_crm_membership_account_kind ON crm_membership(project_account_id, tier_kind) WHERE project_account_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_crm_membership_party_kind ON crm_membership(party_pk, project_id, tier_kind) WHERE project_account_id IS NULL;
DROP INDEX IF EXISTS uq_crm_membership_ext;
CREATE UNIQUE INDEX IF NOT EXISTS uq_crm_membership_ext_kind ON crm_membership(project_id, tier_kind, external_member_id) WHERE external_member_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_crm_membership_account ON crm_membership(project_account_id);

COMMENT ON TABLE crm_membership IS 'One account''s place on one kind of tier ladder in its project: unique per (project_account_id, tier_kind). NULL account only for memberships from before accounts were required.';
COMMENT ON COLUMN crm_membership.project_account_id IS 'The account (in this project) the tier is held by.';
COMMENT ON COLUMN crm_membership.tier_kind IS 'The ladder (crm_tier_kind); current_tier_id is a tier of this kind and project.';
