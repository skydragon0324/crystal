/* site targets against what was actually done */
CREATE VIEW v_crm_location_activity_progress AS
SELECT t.location_activity_target_id,
       t.service_location_id,
       s.location_name,
       t.activity_type_id,
       at.activity_code,
       t.period_start,
       t.period_end,
       t.target_quantity,
       COALESCE(SUM(a.quantity), 0)                    AS actual_quantity,
       t.target_amount,
       COALESCE(SUM(a.amount), 0)                      AS actual_amount,
       CASE WHEN t.target_quantity > 0
            THEN round(COALESCE(SUM(a.quantity), 0) / t.target_quantity * 100, 1) END AS quantity_pct
FROM crm_location_activity_target t
JOIN crm_service_location s       ON s.service_location_id = t.service_location_id
JOIN crm_location_activity_type at ON at.activity_type_id = t.activity_type_id
LEFT JOIN crm_location_activity a ON a.service_location_id = t.service_location_id
                                 AND a.activity_type_id = t.activity_type_id
                                 AND a.status = 'COMPLETED'
                                 AND a.occurred_at >= t.period_start
                                 AND a.occurred_at <  t.period_end + 1
GROUP BY t.location_activity_target_id, s.location_name, at.activity_code;

/* a point account whose cached balance no longer equals its ledger */
CREATE VIEW v_crm_point_account_drift AS
SELECT pa.point_account_id, pa.party_id, pa.point_type_id, pa.balance,
       COALESCE(SUM(pe.points_delta), 0) AS ledger_balance
FROM crm_point_account pa
LEFT JOIN crm_point_event pe ON pe.point_account_id = pa.point_account_id
GROUP BY pa.point_account_id
HAVING pa.balance <> COALESCE(SUM(pe.points_delta), 0);

/* current holders of every instance, one row per active relationship */
CREATE VIEW v_crm_current_holding AS
SELECT r.product_instance_id, i.project_id, i.external_product_instance_id, i.instance_kind,
       p.product_id, p.product_name, p.product_class_id,
       r.party_id, r.relationship_code, r.valid_from, r.product_registration_id
FROM crm_product_registration r
JOIN crm_product_instance i ON i.product_instance_id = r.product_instance_id
JOIN crm_product_catalog  p ON p.product_id = i.product_id
WHERE r.valid_to IS NULL;


