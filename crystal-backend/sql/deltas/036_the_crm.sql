-- Adds section 10 of sql/schema.sql - the Dream CRM tables, their views and
-- triggers, and the seed vocabularies - to a database that was built before
-- it existed. Nothing that already exists is altered.
--
-- It is the same text as that section, so a database migrated forward and one
-- built fresh end up with the same CRM. The migration that runs it
-- (20260930100000_the_crm.js) skips it on a database whose init migration
-- already built section 10 from the current schema.sql - the CREATE TABLEs
-- here are not IF NOT EXISTS, because the seed INSERTs below them are not
-- repeatable either.

CREATE TABLE crm_project (
    project_id                         int            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code                       varchar(30)    NOT NULL UNIQUE,
    project_name                       varchar(150)   NOT NULL,
    project_type_code                  varchar(30)    NULL CHECK (project_type_code IN ('PLATFORM','COMMERCE','SERVICE','SOFTWARE','CONTENT')),
    source_system_code                 varchar(40)    NULL,
    legal_entity_code                  varchar(50)    NULL,
    status                             varchar(20)    NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at                         timestamptz    NOT NULL DEFAULT now(),
    updated_at                         timestamptz    NOT NULL DEFAULT now()
);
COMMENT ON TABLE crm_project IS 'Registry of Dream projects. Each project is one operational source system and therefore the source boundary for external ids. Seeded with PLATFORM, CRYSTAL, EPRODUCT, ESHOP, APPSTORE, KARAOKE, BMEDIA.';

CREATE TABLE crm_currency (
    currency_code                      varchar(3)     PRIMARY KEY,
    currency_name                      varchar(80)    NULL,
    decimal_places                     smallint       NOT NULL DEFAULT 2,
    is_reporting                       boolean        NOT NULL DEFAULT false,
    is_active                          boolean        NOT NULL DEFAULT true
);
COMMENT ON TABLE crm_currency IS 'Currencies used by transactions, costs, rewards and reporting.';
CREATE UNIQUE INDEX uq_crm_currency_reporting ON crm_currency(is_reporting) WHERE is_reporting;

CREATE TABLE crm_location (
    location_id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_location_id                 bigint         NULL REFERENCES crm_location(location_id),
    location_type                      varchar(30)    NOT NULL CHECK (location_type IN ('COUNTRY','PROVINCE','CITY','COUNTY','DISTRICT','TOWN')),
    location_code                      varchar(50)    NULL,
    location_name                      varchar(150)   NOT NULL,
    country_code                       varchar(2)     NULL,
    crystal_province_name              varchar(80)    NULL UNIQUE REFERENCES provinces(name) ON UPDATE CASCADE ON DELETE SET NULL,
    source_location_pk                 bigint         NULL UNIQUE,
    full_name                          varchar(400)   NULL,
    is_active                          boolean        NOT NULL DEFAULT true
);
COMMENT ON TABLE crm_location IS 'Geographic hierarchy (country > province > city > district) for parties, service locations and deliveries. Loaded from Crystal provinces and vendor locations; one system timezone, so no timezone column.';
CREATE INDEX idx_crm_location_parent ON crm_location(parent_location_id);
CREATE INDEX idx_crm_location_type_name ON crm_location(location_type, location_name);

CREATE SEQUENCE crm_party_no_seq;

CREATE TABLE crm_party (
    party_id                           bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_no                           varchar(20)    NOT NULL UNIQUE DEFAULT ('P' || lpad(nextval('crm_party_no_seq')::text, 9, '0')),
    party_type                         varchar(20)    NOT NULL CHECK (party_type IN ('PERSON','ORGANIZATION')),
    party_status                       varchar(20)    NOT NULL DEFAULT 'ACTIVE' CHECK (party_status IN ('ACTIVE','INACTIVE','MERGED','DELETED')),
    display_name                       varchar(250)   NULL,
    origin_project_id                  int            NULL REFERENCES crm_project(project_id),
    merged_into_party_id               bigint         NULL REFERENCES crm_party(party_id),
    first_seen_at                      timestamptz    NULL,
    last_seen_at                       timestamptz    NULL,
    deleted_at                         timestamptz    NULL,
    created_at                         timestamptz    NOT NULL DEFAULT now(),
    updated_at                         timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT chk_crm_party_merged CHECK ((party_status = 'MERGED') = (merged_into_party_id IS NOT NULL)),
    CONSTRAINT chk_crm_party_not_self CHECK (merged_into_party_id IS NULL OR merged_into_party_id <> party_id)
);
COMMENT ON TABLE crm_party IS 'Central identity root. Every person and organization known to Dream gets one party_id.';
CREATE INDEX idx_crm_party_type_status ON crm_party(party_type, party_status);
CREATE INDEX idx_crm_party_origin ON crm_party(origin_project_id);
CREATE INDEX idx_crm_party_name ON crm_party(lower(display_name));

CREATE TABLE crm_person (
    party_id                           bigint         PRIMARY KEY REFERENCES crm_party(party_id) ON DELETE CASCADE,
    full_name                          varchar(250)   NULL,
    gender_code                        varchar(20)    NULL CHECK (gender_code IN ('M','F','OTHER','UNKNOWN')),
    birth_date                         date           NULL,
    birth_year                         smallint       NULL CHECK (birth_year BETWEEN 1900 AND 2100),
    job_title                          varchar(150)   NULL,
    preferred_language                 varchar(20)    NULL,
    nationality_code                   varchar(3)     NULL,
    home_location_id                   bigint         NULL REFERENCES crm_location(location_id),
    address_line                       varchar(255)   NULL,
    id_card_hash                       varchar(64)    NULL,
    id_card_masked                     varchar(20)    NULL,
    created_at                         timestamptz    NOT NULL DEFAULT now(),
    updated_at                         timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT chk_crm_person_birth CHECK (birth_date IS NULL OR birth_year IS NULL OR birth_year = EXTRACT(YEAR FROM birth_date))
);
COMMENT ON TABLE crm_person IS 'Person-only attributes for a PERSON party.';
CREATE INDEX idx_crm_person_id_card ON crm_person(id_card_hash) WHERE id_card_hash IS NOT NULL;

